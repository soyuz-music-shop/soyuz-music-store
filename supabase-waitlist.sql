-- Схема листа ожидания. Уже применена в проекте Supabase soyuz-music-shop.
create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null,
  product_title text not null,
  email text not null,
  customer_name text not null default '',
  notified_at timestamptz,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, product_id)
);

alter table public.waitlist enable row level security;
alter table public.waitlist add column if not exists read_at timestamptz;

drop policy if exists "Users can read own waitlist" on public.waitlist;
create policy "Users can read own waitlist"
on public.waitlist for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can add own waitlist" on public.waitlist;
create policy "Users can add own waitlist"
on public.waitlist for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can remove own waitlist" on public.waitlist;
create policy "Users can remove own waitlist"
on public.waitlist for delete
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can update own waitlist" on public.waitlist;
create policy "Users can update own waitlist"
on public.waitlist for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

grant select, insert, update, delete on table public.waitlist to authenticated;
grant usage, select on sequence public.waitlist_id_seq to authenticated;

create index if not exists waitlist_product_id_idx on public.waitlist (product_id);
create index if not exists waitlist_notified_at_idx on public.waitlist (notified_at);

-- Добровольная подписка пользователя на анонсы новинок.
-- Один пользователь выбирает один режим: все новинки, импортные,
-- российские или новинки конкретного артиста.
create table if not exists public.newsletter_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  customer_name text not null default '',
  enabled boolean not null default false,
  scope text not null default 'all'
    check (scope in ('all', 'import', 'russian', 'artist')),
  artist text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_sent_at timestamptz
);

alter table public.newsletter_preferences enable row level security;

